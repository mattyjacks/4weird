class CritiqueScorecard:
    """Structured evaluation metrics generated by the Critic Agent."""
    def __init__(
        self,
        framing_score: int = 85,
        lighting_score: int = 80,
        safe_zone_score: int = 95,
        audio_score: int = 90,
        pacing_score: int = 85,
        strengths: Optional[List[str]] = None,
        weaknesses: Optional[List[str]] = None,
        actionable_fixes: Optional[List[str]] = None,
        overall_grade: str = "B+"
    ):
        self.framing_score = max(0, min(100, framing_score))
        self.lighting_score = max(0, min(100, lighting_score))
        self.safe_zone_score = max(0, min(100, safe_zone_score))
        self.audio_score = max(0, min(100, audio_score))
        self.pacing_score = max(0, min(100, pacing_score))
        self.overall_score = round(
            (self.framing_score * 0.25) +
            (self.lighting_score * 0.20) +
            (self.safe_zone_score * 0.15) +
            (self.audio_score * 0.20) +
            (self.pacing_score * 0.20),
            1
        )
        self.strengths = strengths or []
        self.weaknesses = weaknesses or []
        self.actionable_fixes = actionable_fixes or []
        self.overall_grade = self._compute_grade()

    def _compute_grade(self) -> str:
        s = self.overall_score
        if s >= 93: return "A+"
        elif s >= 88: return "A"
        elif s >= 83: return "B+"
        elif s >= 78: return "B"
        elif s >= 70: return "C"
        return "D"

    def to_dict(self) -> Dict[str, Any]:
        return {
            "overall_score": self.overall_score,
            "overall_grade": self.overall_grade,
            "scores": {
                "framing_and_composition": self.framing_score,
                "lighting_and_exposure": self.lighting_score,
                "title_safe_clearance": self.safe_zone_score,
                "audio_mastering_lufs": self.audio_score,
                "pacing_and_transitions": self.pacing_score
            },
            "strengths": self.strengths,
            "weaknesses": self.weaknesses,
            "actionable_fixes": self.actionable_fixes
        }


