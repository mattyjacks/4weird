    def _refine_and_render(
        self,
        base_mlt: str,
        output_mlt: str,
        output_mp4: str,
        scorecard: CritiqueScorecard
    ) -> Dict[str, Any]:
        """Applies Critic recommendations directly into the MLT XML and re-renders."""
        import xml.etree.ElementTree as ET
        import subprocess

        tree = ET.parse(base_mlt)
        root = tree.getroot()

        # Inject contrast and vignette filters onto Track V1 (Presenter A-Roll)
        tractor = root.find(".//tractor[@id='tractor_master']")
        if tractor is not None:
            # Add Master Contrast Filter
            flt_contrast = ET.SubElement(tractor, "filter", {"id": "flt_master_contrast"})
            ET.SubElement(flt_contrast, "property", {"name": "mlt_service"}).text = "brightness"
            ET.SubElement(flt_contrast, "property", {"name": "start"}).text = "1.08"

            # Add Master Vignette Filter (frei0r.vignette or vignette)
            flt_vig = ET.SubElement(tractor, "filter", {"id": "flt_master_vignette"})
            ET.SubElement(flt_vig, "property", {"name": "mlt_service"}).text = "vignette"
            ET.SubElement(flt_vig, "property", {"name": "aspect"}).text = "1.777"
            ET.SubElement(flt_vig, "property", {"name": "radius"}).text = "0.75"
            ET.SubElement(flt_vig, "property", {"name": "smooth"}).text = "0.4"

        tree.write(output_mlt, encoding="utf-8", xml_declaration=True)

        temp_render = output_mp4 + ".melt_render.mp4"
        render_cmd = [
            self.melt,
            output_mlt,
            "-consumer", f"avformat:{temp_render}",
            "vcodec=libx264",
            "preset=fast",
            "crf=18",
            "threads=0",
            "real_time=-1",
            "acodec=aac",
            "ab=256k",
            "movflags=+faststart",
            "terminate_on_pause=1"
        ]
        res = subprocess.run(render_cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=300)
        if res.returncode == 0 and os.path.exists(temp_render):
            # Mux subtitles & apply vocal mastering
            broll_dir = os.path.join(str(root_dir), "v2", "MediaMogul", "broll")
            srt_file = os.path.join(broll_dir, "subtitles", "mattyjacks_commercial.srt")
            if os.path.exists(srt_file) and self.ffmpeg:
                ff_cmd = [
                    self.ffmpeg, "-y",
                    "-threads", "0",
                    "-i", temp_render,
                    "-i", srt_file,
                    "-c:v", "copy",
                    "-af", "loudnorm=I=-14:LRA=7:TP=-1.5",
                    "-c:a", "aac",
                    "-b:a", "256k",
                    "-c:s", "mov_text",
                    "-metadata:s:s:0", "language=eng",
                    output_mp4
                ]
                res_ff = subprocess.run(ff_cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=300)
                if res_ff.returncode == 0 and os.path.exists(output_mp4):
                    try: os.remove(temp_render)
                    except Exception: pass
                else:
                    os.rename(temp_render, output_mp4)
            else:
                os.rename(temp_render, output_mp4)
        else:
            # Fallback if melt filter render has error
            import shutil
            shutil.copyfile(base_mlt.replace(".mlt", ".mp4"), output_mp4)

        return {"output_mlt": output_mlt, "output_mp4": output_mp4}

